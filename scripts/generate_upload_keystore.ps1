<#
.SYNOPSIS
    Generates an Android upload keystore (`android/upload-keystore.jks`) and
    `android/key.properties` for Google Play App Signing.
.DESCRIPTION
    Locates `keytool.exe` via `$env:JAVA_HOME`, `$env:LOCALAPPDATA\Programs\OpenJDK21\bin`,
    or system `PATH`. Generates a 2048-bit RSA keystore and writes gitignored
    `android/key.properties`. Refuses to overwrite an existing keystore unless `-Force` is set.
#>
[CmdletBinding()]
param(
    [string]$KeyAlias = "upload",
    [string]$StorePassword = "",
    [string]$KeyPassword = "",
    [string]$DName = "CN=MASHWAR Qatar, OU=Mobile Engineering, O=MASHWAR, L=Doha, ST=Doha, C=QA",
    [int]$ValidityDays = 10000,
    [string]$KeystorePath = "",
    [string]$KeyPropertiesPath = "",
    [switch]$Force
)

$ErrorActionPreference = "Stop"

$repoRoot = Split-Path -Parent $PSScriptRoot
$androidDir = Join-Path $repoRoot "android"

if ([string]::IsNullOrWhiteSpace($KeystorePath)) {
    $KeystorePath = Join-Path $androidDir "upload-keystore.jks"
}
if ([string]::IsNullOrWhiteSpace($KeyPropertiesPath)) {
    $KeyPropertiesPath = Join-Path $androidDir "key.properties"
}

function Resolve-KeytoolPath {
    $candidates = @()
    if (-not [string]::IsNullOrWhiteSpace($env:JAVA_HOME)) {
        $candidates += (Join-Path $env:JAVA_HOME "bin\keytool.exe")
    }
    if (-not [string]::IsNullOrWhiteSpace($env:LOCALAPPDATA)) {
        $candidates += (Join-Path $env:LOCALAPPDATA "Programs\OpenJDK21\bin\keytool.exe")
    }
    $pathCmd = Get-Command keytool.exe -ErrorAction SilentlyContinue
    if ($null -ne $pathCmd -and -not [string]::IsNullOrWhiteSpace($pathCmd.Source)) {
        $candidates += $pathCmd.Source
    }

    foreach ($candidate in $candidates) {
        if (Test-Path -LiteralPath $candidate) {
            return $candidate
        }
    }

    throw "keytool.exe not found. Set JAVA_HOME or install OpenJDK 21 under `$env:LOCALAPPDATA\Programs\OpenJDK21`."
}

function New-RandomSecret {
    param([int]$Length = 24)
    $alphabet = "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789!@#%^*_-"
    $bytes = New-Object byte[] $Length
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try {
        $rng.GetBytes($bytes)
    } finally {
        $rng.Dispose()
    }
    $chars = for ($i = 0; $i -lt $Length; $i++) {
        $alphabet[$bytes[$i] % $alphabet.Length]
    }
    return (-join $chars)
}

if ((Test-Path -LiteralPath $KeystorePath) -and (-not $Force)) {
    throw "Keystore already exists at '$KeystorePath'. Back it up first or pass -Force to overwrite."
}

if ([string]::IsNullOrWhiteSpace($StorePassword)) {
    $StorePassword = New-RandomSecret -Length 28
}
if ([string]::IsNullOrWhiteSpace($KeyPassword)) {
    $KeyPassword = $StorePassword
}

$keytoolExe = Resolve-KeytoolPath
Write-Host "Using keytool: $keytoolExe" -ForegroundColor Cyan

$keystoreParent = Split-Path -Parent $KeystorePath
if (-not (Test-Path -LiteralPath $keystoreParent)) {
    New-Item -ItemType Directory -Path $keystoreParent -Force | Out-Null
}
if ((Test-Path -LiteralPath $KeystorePath) -and $Force) {
    Remove-Item -LiteralPath $KeystorePath -Force
}

& $keytoolExe `
    -genkeypair `
    -v `
    -keystore $KeystorePath `
    -storetype PKCS12 `
    -keyalg RSA `
    -keysize 2048 `
    -validity $ValidityDays `
    -alias $KeyAlias `
    -storepass $StorePassword `
    -keypass $KeyPassword `
    -dname $DName

if ($LASTEXITCODE -ne 0 -or -not (Test-Path -LiteralPath $KeystorePath)) {
    throw "keytool failed with exit code $LASTEXITCODE."
}

$storeFileValue = [System.IO.Path]::GetFileName($KeystorePath)
if ((Split-Path -Parent ([System.IO.Path]::GetFullPath($KeystorePath))) -ne (Split-Path -Parent ([System.IO.Path]::GetFullPath($KeyPropertiesPath)))) {
    $storeFileValue = ($KeystorePath -replace "\\", "/")
}

$propsContent = @(
    "# Generated by scripts/generate_upload_keystore.ps1 (GITIGNORED - DO NOT COMMIT)"
    "storePassword=$StorePassword"
    "keyPassword=$KeyPassword"
    "keyAlias=$KeyAlias"
    "storeFile=$storeFileValue"
) -join "`n"

[System.IO.File]::WriteAllText($KeyPropertiesPath, "$propsContent`n", [System.Text.UTF8Encoding]::new($false))

Write-Host "Generated upload keystore: $KeystorePath" -ForegroundColor Green
Write-Host "Generated signing config : $KeyPropertiesPath" -ForegroundColor Green
Write-Host "IMPORTANT: Back up both files in your team secret vault immediately. Never commit them to Git." -ForegroundColor Yellow
